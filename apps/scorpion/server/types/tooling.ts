// ---- Conversation scratchpad (executor memory for this turn)

export type ScratchpadEntry = {
  callId: string;
  tool: string;
  timestamp: number;
  result: ToolResult<any>;
};

export type Scratchpad = {
  conversationId: string;
  entries: ScratchpadEntry[];
  put: (e: ScratchpadEntry) => void;
  last: () => ScratchpadEntry | undefined;
};

// Thin in-memory default (swap with Redis if you want)
export function createScratchpad(conversationId: string): Scratchpad {
  const entries: ScratchpadEntry[] = [];
  return {
    conversationId,
    entries,
    put: (e) => entries.push(e),
    last: () => entries[entries.length - 1],
  };
}

