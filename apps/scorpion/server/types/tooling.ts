// ---- Core tool contract (uniform across all tools) - Tool Layer v2

export type ToolOK<T = unknown> = {
  ok: true;
  data: T;
  error?: undefined;
  meta?: {
    provider?: string;
    took_ms?: number;
    retries?: number;
    source?: string;
    [k: string]: unknown;
  };
};

export type ToolERR = {
  ok: false;
  data?: undefined;
  error: {
    code: string;
    message: string;
    details?: any;
  };
  meta?: {
    provider?: string;
    took_ms?: number;
    retries?: number;
    code?: string | number;
    [k: string]: unknown;
  };
};

export type ToolResult<T = unknown> = ToolOK<T> | ToolERR;

export type ToolInvokeArgs = {
  callId: string;                 // generated by executor
  conversationId: string;
  userId?: string;
  // raw args passed by plan step
  args: Record<string, unknown>;
  // deadline / timeouts / retries
  timeout_ms?: number;
  attempt?: number;
};

