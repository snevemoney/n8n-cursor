import { NextRequest, NextResponse } from 'next/server';
import { runCouncil } from '@/server/council';
import { extractDomainTags } from '@/server/council/runCouncil';
import type { CouncilInput, CouncilResult } from '@/server/types/council';

export const dynamic = 'force-dynamic';

type LanguageStyle = 'dev' | 'gamer' | 'spy' | 'normal';
type Period = 'daily' | 'weekly' | 'monthly';

interface ConsolidatedReportRequest {
  period: Period;
  style: LanguageStyle;
  workflows: Array<{
    workflowName: string;
    status: 'success' | 'failure' | 'cancelled';
    branch: string;
    commitSha: string;
    commitMessage: string;
    timestamp: string;
    changedFiles?: string[];
    errorMessages?: string[];
  }>;
}

