#!/usr/bin/env bash
# sync_tools.sh — REPORT-ONLY registry sync. Copies/overwrites/installs nothing.
#   ./sync_tools.sh box          -> runs box verify cmds, writes out/box.json, out/mac_checks.sh, out/vps_checks_for_forge.sh
#   (run out/mac_checks.sh on the Mac read-only, e.g. via Shell machineId <mac-machine-id>..., save stdout to out/mac.jsonl)
#   ./sync_tools.sh report       -> merges box + mac (+ out/vps.jsonl if Forge returns it) into SYNC_RESULTS.md / .json
set -u
D="$(cd "$(dirname "$0")" && pwd)"; mkdir -p "$D/out"
exec python3 - "$D" "${1:-box}" <<'PY'
import json,sys,os,subprocess,shlex,collections
D,mode=sys.argv[1],sys.argv[2]; O=D+"/out"; REG=json.load(open(D+"/TOOLS_REGISTRY.json"))["tools"]
SKDIRS=["~/.claude/skills","~/.cursor/skills","~/.codex/skills"]
def skill_names(root):
    n=set()
    if root and os.path.isdir(root):
        for dp,dn,fn in os.walk(root):
            dn[:]=[d for d in dn if d not in ("node_modules",".git",".venv")]
            if "SKILL.md" in fn: n.add(os.path.basename(dp))
    return sorted(n)
def line(kind,name,cmd):  # emits a shell line that prints one JSON result; read-only commands only
    return f"( {cmd} ) >/dev/null 2>&1 </dev/null; printf '%s\\n' \"{{\\\"kind\\\":\\\"{kind}\\\",\\\"name\\\":\\\"{name}\\\",\\\"ok\\\":$([ $? -eq 0 ] && echo true || echo false)}}\""
if mode=="box":
    res=[]
    for t in REG:
        b=t["machines"].get("box")
        if not b: continue
        try: rc=subprocess.run(b["verify"],shell=True,capture_output=True,timeout=90,stdin=subprocess.DEVNULL).returncode
        except subprocess.TimeoutExpired: rc=124
        res.append({"name":t["name"],"ok":rc==0,"rc":rc})
    packs={t["name"]:skill_names(t["skill_pack"]) for t in REG if t.get("skill_pack")}
    box_skills={d:(set(os.listdir(os.path.expanduser(d))) if os.path.isdir(os.path.expanduser(d)) else None) for d in SKDIRS}
    json.dump({"verify":res,"packs":packs,"box_skill_dirs":{d:(None if s is None else len(s)) for d,s in box_skills.items()},
               "box_missing":{p:{d:(len(n) if s is None else len([x for x in n if x not in s])) for d,s in box_skills.items()} for p,n in packs.items()}},open(O+"/box.json","w"),indent=1)
    with open(O+"/mac_checks.sh","w") as f:
        f.write("#!/bin/bash\n# READ-ONLY Mac checks generated by sync_tools.sh (test/ls/--version only)\nexport PATH=/opt/homebrew/bin:/usr/local/bin:$PATH\n")
        for t in REG:
            m=t["machines"].get("mac")
            if m: f.write(line("verify",t["name"],"timeout 60 bash -c "+shlex.quote(m["verify"]) if False else m["verify"])+"\n")
        f.write('for d in ~/.claude/skills ~/.cursor/skills ~/.codex/skills; do echo "##DIR $d $([ -d "$d" ] && echo present || echo absent)"; ls -1 "$d" 2>/dev/null; done\n')
    with open(O+"/vps_checks_for_forge.sh","w") as f:
        f.write("#!/bin/bash\n# For Forge on the VPS (box outbound SSH blocked). READ-ONLY: test/ls/--version. Save stdout as vps.jsonl and return it.\n")
        for t in REG:
            v=t["machines"].get("vps")
            if v and v["path"]!="(not installed)":
                f.write(line("exists",t["name"],"test -e "+shlex.quote(v["path"]))+"\n"); f.write(line("verify",t["name"],v["verify"])+"\n")
        f.write("for d in ~/.claude/skills ~/.cursor/skills ~/.codex/skills; do printf '{\"kind\":\"skilldir\",\"dir\":\"%s\",\"count\":%s}\\n' \"$d\" \"$(ls \"$d\" 2>/dev/null | wc -l)\"; done\n")
    os.chmod(O+"/mac_checks.sh",0o755); os.chmod(O+"/vps_checks_for_forge.sh",0o755)
    print("box verify:",collections.Counter("ok" if r["ok"] else "FAIL" for r in res)); [print("  FAIL",r) for r in res if not r["ok"]]
elif mode=="report":
    B=json.load(open(O+"/box.json")); R={t["name"]:t for t in REG}
    def jl(p): return [json.loads(l) for l in open(p) if l.strip().startswith("{")] if os.path.exists(p) else []
    mac=jl(O+"/mac.jsonl"); vps=jl(O+"/vps.jsonl")
    mv={r["name"]:r["ok"] for r in mac if r["kind"]=="verify"}; vv={r["name"]:r["ok"] for r in vps if r["kind"]=="verify"}
    bv={r["name"]:r["ok"] for r in B["verify"]}
    rows=[];gaps=[]
    for n,t in R.items():
        cell=lambda mach,d: "—" if mach not in t["machines"] else ("pending(Forge)" if mach=="vps" and n not in d else ("ok" if d.get(n) else "FAIL"))
        r={"name":n,"status":t["status"],"box":cell("box",bv),"mac":cell("mac",mv),"vps":cell("vps",vv)}; rows.append(r)
        for k in ("box","mac"):
            if r[k]=="FAIL": gaps.append(f"{n}: {k} verify failed ({t['machines'][k]['verify']})")
    dirs={};cur=None
    if os.path.exists(O+"/mac.jsonl"):
        for l in open(O+"/mac.jsonl"):
            l=l.rstrip("\n")
            if l.startswith("##DIR "):
                _,d,st=l.split(" "); home=os.path.expanduser("~"); d=d.replace("~","~"); cur=d; dirs[d]=set() if st=="present" else None
            elif cur and l and not l.startswith("{") and dirs[cur] is not None: dirs[cur].add(l.strip())
    miss=collections.defaultdict(dict)
    for p,n in B["packs"].items():
        for d,s in dirs.items():
            m=n if s is None else [x for x in n if x not in s]; miss[p][d]=(len(m),len(n),m[:8])
    json.dump({"rows":rows,"gaps":gaps,"mac_skill_missing":miss,"box_skill_dirs":B["box_skill_dirs"]},open(D+"/SYNC_RESULTS.json","w"),indent=1)
    L=["# Tool registry sync results (report-only)","",f"Rows: {len(rows)}. Box/Mac verified by command; VPS pending Forge (`out/vps_checks_for_forge.sh`).","","| Tool | Status | Box | Mac | VPS |","|---|---|---|---|---|"]
    L+=[f"| {r['name']} | {r['status']} | {r['box']} | {r['mac']} | {r['vps']} |" for r in rows]
    L+=["","## Verify gaps"]+([f"- {g}" for g in gaps] or ["- none"])
    L+=["","## Skill packs missing from agent skill dirs (Mac: missing/total; examples)","","| Pack | ~/.claude/skills | ~/.cursor/skills | ~/.codex/skills |","|---|---|---|---|"]
    for p,d in sorted(miss.items()):
        L.append(f"| {p} | "+" | ".join(f"{d[k][0]}/{d[k][1]}" for k in ["~/.claude/skills","~/.cursor/skills","~/.codex/skills"] if k in d)+" |")
    L+=["","Missing examples (first 8, Claude dir):"]+[f"- {p}: {', '.join(d.get('~/.claude/skills',(0,0,[]))[2])}" for p,d in sorted(miss.items()) if d.get('~/.claude/skills',(0,))[0]]
    L+=["",f"Box agent skill dirs: {B['box_skill_dirs']} (None = dir absent; box is not an agent-skill host, so every pack counts as missing there)."]
    open(D+"/SYNC_RESULTS.md","w").write("\n".join(L)+"\n"); print("\n".join(L[-12:])); print("gaps:",len(gaps))
PY
